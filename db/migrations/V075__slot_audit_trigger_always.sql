-- 2) One-time: harden every existing audit trigger not already ALWAYS (mirrors V070 step 5, re-run
--    to catch slots provisioned between V070 and this migration).
DO $$
DECLARE r record;
BEGIN
  FOR r IN
    SELECT n.nspname AS sch, c.relname AS tbl, t.tgname AS trg
    FROM pg_trigger t
    JOIN pg_class c ON c.oid = t.tgrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE NOT t.tgisinternal AND t.tgname LIKE '%audit%' AND t.tgenabled <> 'A'
  LOOP
    EXECUTE format('ALTER TABLE %I.%I ENABLE ALWAYS TRIGGER %I', r.sch, r.tbl, r.trg);
  END LOOP;
END $$;
