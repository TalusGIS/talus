-- V064 — GeoServices OBJECTID: a per-layer int32 identity on every hosted feature table
-- (decision-interop-i3.md §2.3, fork 1 — CONFIRMED 2026-07-07).
--
-- Why: Esri REST clients require stable INTEGER object ids. QGIS's AFS provider does
-- `objectId.toInt()` (int32 — the recon-verified bound; int64 would silently wrap) and
-- harvests ALL ids in one returnIdsOnly call, so ids must be real, persistent, and unique
-- per layer. Talus feature identity stays the uuid `id` everywhere else; `objectid` is the
-- desktop-dialect alias, born on every table and never reused.
--
-- Design choices (the decision doc's record, restated where it matters to THIS file):
--   * `integer` (int32), NOT bigint — the QGIS bound; 2.1B features/layer is not a
--     municipal constraint.
--   * GENERATED BY DEFAULT (not ALWAYS) — restore tooling (T47 restore-item) merges rows
--     with EXPLICIT objectid values to preserve desktop identity across recovery; the
--     sequence is then resynced by that tooling (setval to max(objectid)).
--   * The column is added/declared LAST — migrated tables get it last (ADD COLUMN), so the
--     provisioner templates also put it last, keeping physical column order identical
--     across old and new tables (the restore scripts' INSERT..SELECT * discipline).
--   * Backfill is deterministic (row_number() ORDER BY created_at, id) with USER triggers
--     disabled for the backfill UPDATE only — no audit spam, no row_version churn, no
--     props re-validation for a pure aliasing operation. The DO block iterates real TABLES
--     only (pg_class relkind 'r'): view layers (vw_*, T38) are PG views and are excluded —
--     they don't serve over FeatureServer in v1 (decision doc §3 fork 1/5 note).

-- 1) The spatial provisioner grows the column (full replacement of V061's function). ------------
CREATE OR REPLACE FUNCTION platform.provision_spatial_layer(p_id text, p_geom_type text, p_srid integer)
RETURNS void
LANGUAGE plpgsql
AS $fn$
DECLARE
  v_pg_type text;
BEGIN
  v_pg_type := CASE p_geom_type
                 WHEN 'point'   THEN 'Point'
                 WHEN 'line'    THEN 'MultiLineString'
                 WHEN 'polygon' THEN 'MultiPolygon'
               END;
  IF v_pg_type IS NULL THEN
    RAISE EXCEPTION 'provision_spatial_layer: invalid geom_type %', p_geom_type;
  END IF;
  IF p_id !~ '^tal_[0-9a-f]{8}$' THEN
    RAISE EXCEPTION 'provision_spatial_layer: invalid layer id %', p_id;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.spatial_ref_sys WHERE srid = p_srid) THEN
    RAISE EXCEPTION 'provision_spatial_layer: unknown srid %', p_srid;
  END IF;

  -- The V061 slot shape + V064 objectid (last — see header).
  EXECUTE format($ddl$
    CREATE TABLE assets.%I (
      id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
      geom           geometry(%s, %s) NOT NULL,
      created_at     timestamptz NOT NULL DEFAULT now(),
      created_by     uuid NOT NULL REFERENCES platform.users(id),
      updated_at     timestamptz NOT NULL DEFAULT now(),
      updated_by     uuid NOT NULL REFERENCES platform.users(id),
      ai_provenance  jsonb,
      notes          text,
      row_version    bigint NOT NULL DEFAULT pg_current_xact_id()::text::bigint,
      props          jsonb NOT NULL DEFAULT '{}'::jsonb,
      objectid       integer NOT NULL GENERATED BY DEFAULT AS IDENTITY UNIQUE
    )
  $ddl$, p_id, v_pg_type, p_srid);

  EXECUTE format('CREATE INDEX %I ON assets.%I USING GIST (geom)', p_id || '_geom_idx', p_id);
  EXECUTE format('CREATE INDEX %I ON assets.%I USING GIN (props)', p_id || '_props_idx', p_id);
  EXECUTE format(
    'CREATE INDEX %I ON assets.%I USING GIN (assets.search_document(notes, props))',
    p_id || '_search_idx', p_id
  );

  EXECUTE format($ddl$
    CREATE TABLE audit.%I (
      audit_id     bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
      asset_id     uuid NOT NULL,
      operation    text NOT NULL CHECK (operation IN ('INSERT','UPDATE','DELETE')),
      changed_at   timestamptz NOT NULL DEFAULT now(),
      changed_by   uuid REFERENCES platform.users(id),
      actor_type   text NOT NULL DEFAULT 'human' CHECK (actor_type IN ('human','ai_inference','service_account')),
      provenance   jsonb,
      client_info  jsonb,
      before_row   jsonb,
      after_row    jsonb
    )
  $ddl$, p_id || '_audit');
  EXECUTE format('CREATE INDEX %I ON audit.%I (asset_id)',   p_id || '_audit_asset_idx',   p_id || '_audit');
  EXECUTE format('CREATE INDEX %I ON audit.%I (changed_at)', p_id || '_audit_changed_idx', p_id || '_audit');

  EXECUTE format(
    'CREATE TRIGGER %I AFTER INSERT OR UPDATE OR DELETE ON assets.%I '
    'FOR EACH ROW EXECUTE FUNCTION audit.fn_record_change(%L, %L)',
    p_id || '_audit_trigger', p_id, 'audit.' || p_id || '_audit', 'id'
  );
  EXECUTE format(
    'CREATE TRIGGER %I BEFORE INSERT OR UPDATE ON assets.%I '
    'FOR EACH ROW EXECUTE FUNCTION assets.fn_validate_layer_props()',
    p_id || '_props_validate_trigger', p_id
  );
  EXECUTE format(
    'CREATE TRIGGER %I BEFORE UPDATE ON assets.%I '
    'FOR EACH ROW EXECUTE FUNCTION assets.fn_bump_row_version()',
    p_id || '_row_version_trigger', p_id
  );
END;
$fn$;

COMMENT ON FUNCTION platform.provision_spatial_layer(text, text, integer) IS
  'decision-slot-provisioning.md + decision-interop-i3.md (V064 objectid): scoped, template-fixed '
  'creation of one hosted SPATIAL layer (current slot schema + GeoServices objectid identity, geom '
  'born at the requested family/SRID). Called by the API create path; id is app-generated + '
  'collision-checked and matches ^tal_[0-9a-f]{8}$.';

