-- 3) Backfill every EXISTING hosted feature table (built-ins + tal_*; tables and spatial alike).
-- Real tables only (relkind 'r') — vw_* view layers are PG views and take no identity column.
DO $$
DECLARE
  r record;
  v_max integer;
  v_order text;
BEGIN
  FOR r IN
    SELECT l.layer_id
    FROM platform.layers l
    JOIN pg_class c ON c.relname = l.layer_id AND c.relnamespace = 'assets'::regnamespace
    WHERE c.relkind = 'r'
      AND NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'assets' AND table_name = l.layer_id AND column_name = 'objectid'
      )
  LOOP
    EXECUTE format('ALTER TABLE assets.%I ADD COLUMN objectid integer', r.layer_id);

    -- Deterministic backfill, triggers silenced: pure aliasing, not a data edit — no audit
    -- rows, no row_version bumps, no props re-validation. Chronological order where the table
    -- HAS created_at (the slot schema); plain id order for pre-slot legacy imports that don't
    -- (county_boundary — reference data with no audit columns; any stable order is correct,
    -- ids only need to be persistent from this moment on).
    IF EXISTS (
      SELECT 1 FROM information_schema.columns
      WHERE table_schema = 'assets' AND table_name = r.layer_id AND column_name = 'created_at'
    ) THEN
      v_order := 'created_at, id';
    ELSE
      v_order := 'id';
    END IF;
    EXECUTE format('ALTER TABLE assets.%I DISABLE TRIGGER USER', r.layer_id);
    EXECUTE format(
      'UPDATE assets.%I t SET objectid = s.rn '
      'FROM (SELECT id, row_number() OVER (ORDER BY %s) AS rn FROM assets.%I) s '
      'WHERE t.id = s.id',
      r.layer_id, v_order, r.layer_id
    );
    EXECUTE format('ALTER TABLE assets.%I ENABLE TRIGGER USER', r.layer_id);

    EXECUTE format('ALTER TABLE assets.%I ALTER COLUMN objectid SET NOT NULL', r.layer_id);
    EXECUTE format('SELECT coalesce(max(objectid), 0) FROM assets.%I', r.layer_id) INTO v_max;
    EXECUTE format(
      'ALTER TABLE assets.%I ALTER COLUMN objectid ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)',
      r.layer_id, v_max + 1
    );
    EXECUTE format(
      'ALTER TABLE assets.%I ADD CONSTRAINT %I UNIQUE (objectid)',
      r.layer_id, r.layer_id || '_objectid_key'
    );
  END LOOP;
END $$;
