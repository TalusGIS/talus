-- V065 — audit actor_type CHECK: admit 'service_account' on aspatial audit shadows.
--
-- The latent bug (found during V064 review, 2026-07-07): V059's provision_hosted_table
-- audit-shadow template declared actor_type CHECK IN ('human','ai_inference') — missing
-- 'service_account', which the spatial template (V061) and every older audit shadow have.
-- A T19 service account with edit access writing a feature to an ASPATIAL hosted table
-- stamps actor_type='service_account' (audit_context.actor_type_for), the AFTER-trigger
-- audit INSERT violates the CHECK, and the whole write aborts with a 500 — un-bypassable
-- audit doing its job against a wrong allow-list. One live table is affected
-- (audit.tal_44b14916_audit); V064 carried the narrow template forward faithfully, so
-- without this fix every future aspatial table would inherit it.
--
-- Two moves: (1) widen the CHECK on ANY audit shadow that lacks 'service_account'
-- (generic — heals restored/drilled schemas too, idempotent by construction);
-- (2) re-declare provision_hosted_table with the correct 3-value CHECK (the ONLY change
-- from V064's version).

-- 1) Heal existing audit shadows. ----------------------------------------------------------------
DO $$
DECLARE
  r record;
BEGIN
  FOR r IN
    SELECT conrelid::regclass::text AS tbl, conname
    FROM pg_constraint
    WHERE connamespace = 'audit'::regnamespace
      AND contype = 'c'
      AND conname LIKE '%actor_type%'
      AND pg_get_constraintdef(oid) NOT LIKE '%service_account%'
  LOOP
    EXECUTE format('ALTER TABLE %s DROP CONSTRAINT %I', r.tbl, r.conname);
    EXECUTE format(
      'ALTER TABLE %s ADD CONSTRAINT %I CHECK (actor_type IN (''human'',''ai_inference'',''service_account''))',
      r.tbl, r.conname
    );
  END LOOP;
END $$;

-- 2) Fix the aspatial provisioner template (full replacement of V064's version; the audit
--    CHECK gains 'service_account' — no other change). -------------------------------------------
CREATE OR REPLACE FUNCTION platform.provision_hosted_table(p_id text)
RETURNS void
LANGUAGE plpgsql
AS $fn$
BEGIN
  EXECUTE format($ddl$
    CREATE TABLE assets.%I (
      id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
      created_at     timestamptz NOT NULL DEFAULT now(),
      created_by     uuid NOT NULL REFERENCES platform.users(id),
      updated_at     timestamptz NOT NULL DEFAULT now(),
      updated_by     uuid NOT NULL REFERENCES platform.users(id),
      ai_provenance  jsonb,
      notes          text,
      row_version    bigint NOT NULL DEFAULT pg_current_xact_id()::text::bigint,
      props          jsonb NOT NULL DEFAULT '{}'::jsonb,
      objectid       integer NOT NULL GENERATED BY DEFAULT AS IDENTITY UNIQUE
    )
  $ddl$, p_id);

  EXECUTE format('CREATE INDEX %I ON assets.%I USING GIN (props)', p_id || '_props_idx', p_id);
  EXECUTE format(
    'CREATE INDEX %I ON assets.%I USING GIN (assets.search_document(notes, props))',
    p_id || '_search_idx', p_id
  );

  EXECUTE format($ddl$
    CREATE TABLE audit.%I (
      audit_id     bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
      asset_id     uuid NOT NULL,
      operation    text NOT NULL CHECK (operation IN ('INSERT','UPDATE','DELETE')),
      changed_at   timestamptz NOT NULL DEFAULT now(),
      changed_by   uuid REFERENCES platform.users(id),
      actor_type   text NOT NULL DEFAULT 'human' CHECK (actor_type IN ('human','ai_inference','service_account')),
      provenance   jsonb,
      client_info  jsonb,
      before_row   jsonb,
      after_row    jsonb
    )
  $ddl$, p_id || '_audit');
  EXECUTE format('CREATE INDEX %I ON audit.%I (asset_id)',  p_id || '_audit_asset_idx',   p_id || '_audit');
  EXECUTE format('CREATE INDEX %I ON audit.%I (changed_at)', p_id || '_audit_changed_idx', p_id || '_audit');

  EXECUTE format(
    'CREATE TRIGGER %I AFTER INSERT OR UPDATE OR DELETE ON assets.%I '
    'FOR EACH ROW EXECUTE FUNCTION audit.fn_record_change(%L, %L)',
    p_id || '_audit_trigger', p_id, 'audit.' || p_id || '_audit', 'id'
  );
  EXECUTE format(
    'CREATE TRIGGER %I BEFORE INSERT OR UPDATE ON assets.%I '
    'FOR EACH ROW EXECUTE FUNCTION assets.fn_validate_layer_props()',
    p_id || '_props_validate_trigger', p_id
  );
  EXECUTE format(
    'CREATE TRIGGER %I BEFORE UPDATE ON assets.%I '
    'FOR EACH ROW EXECUTE FUNCTION assets.fn_bump_row_version()',
    p_id || '_row_version_trigger', p_id
  );
END;
$fn$;

COMMENT ON FUNCTION platform.provision_hosted_table(text) IS
  'decision-nonspatial-tables.md + decision-interop-i3.md (V064 objectid, V065 audit actor fix): '
  'scoped, template-fixed creation of one aspatial hosted-table asset (slot schema minus '
  'geom/GiST/tile, plus the GeoServices objectid identity). Called by the API create-table path; '
  'the id is app-generated + collision-checked and matches ^tal_[0-9a-f]{8}$.';
